// Smoke test for the professional PDF layout (backend/src/routes/reports.js):
// renders a real multi-page PDF with the header, key/value block and table
// helpers, and generates a real QR code buffer from an admit-card payload.
// No database needed. Run: node --test test/*.test.js (from backend/)
const test = require('node:test');
const assert = require('node:assert/strict');
const PDFDocument = require('pdfkit');
const QRCode = require('qrcode');
const reports = require('../src/routes/reports');

const { drawReportHeader, drawKeyValues, renderPdfTable, finishPdf } = reports.__test;

// pdfkit writes text as hex strings inside TJ arrays (sometimes split
// into fragments with kerning adjustments), so plain-text search on the
// raw bytes fails. Decode every <hex> fragment and join them.
function extractPdfText(buf) {
  const raw = buf.toString('latin1');
  const parts = [];
  for (const m of raw.matchAll(/<([0-9a-fA-F]+)>/g)) {
    parts.push(Buffer.from(m[1], 'hex').toString('latin1'));
  }
  return parts.join('');
}

function renderToBuffer(build) {
  return new Promise((resolve, reject) => {
    // compress: false so the test can assert on the visible text in the
    // raw bytes (production PDFs keep pdfkit's default compression).
    const doc = new PDFDocument({ margin: 40, size: 'A4', bufferPages: true, compress: false });
    const chunks = [];
    doc.on('data', (c) => chunks.push(c));
    doc.on('end', () => resolve(Buffer.concat(chunks)));
    doc.on('error', reject);
    build(doc);
    finishPdf(doc);
  });
}

test('PDF export renders a valid multi-page document with header and table', async () => {
  const rows = Array.from({ length: 60 }, (_, i) => [
    `STU-${String(i + 1).padStart(3, '0')}`,
    `Student Number ${i + 1} With A Fairly Long Name`,
    `student${i + 1}@example.com`,
    'Computer Science',
    String((i % 8) + 1),
    'active',
  ]);
  const buf = await renderToBuffer((doc) => {
    drawReportHeader(doc, 'Student List', 'Registered students');
    drawKeyValues(doc, [['Total students', '60'], ['Generated by', 'test']]);
    renderPdfTable(doc, ['ID', 'Name', 'Email', 'Department', 'Semester', 'Status'], rows);
  });
  assert.equal(buf.subarray(0, 5).toString(), '%PDF-', 'output is a real PDF');
  assert.ok(buf.length > 5000, `PDF has real content (got ${buf.length} bytes)`);
  // 60 rows cannot fit on one A4 page — the table must paginate, and the
  // footer must carry a page count.
  const text = extractPdfText(buf);
  assert.match(text, /Page 2 of \d+/, 'multi-page PDF carries "Page X of Y" footers');
  assert.match(text, /University Examination Department/, 'university header is in the PDF');
});

test('PDF table renders "No records found" for an empty result set', async () => {
  const buf = await renderToBuffer((doc) => {
    drawReportHeader(doc, 'Published Results', 'Examination #1');
    renderPdfTable(doc, ['Student ID', 'Name', 'Subject'], []);
  });
  assert.equal(buf.subarray(0, 5).toString(), '%PDF-');
  assert.match(extractPdfText(buf), /No records found/);
});

test('admit-card QR payload generates a real PNG QR code locally', async () => {
  const ref = reports.buildAdmitCardRef('STU-2026-001', 2);
  const payload = reports.buildAdmitCardPayload({
    ref, studentCode: 'STU-2026-001', studentName: 'Test Student', examId: 2,
  });
  const png = await QRCode.toBuffer(payload, { errorCorrectionLevel: 'M', margin: 1, width: 480 });
  // PNG magic bytes — proves the QR is generated by the local `qrcode`
  // package, not fetched from any external service.
  assert.deepEqual([...png.subarray(0, 8)], [0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]);
  assert.ok(png.length > 500, `QR PNG has real content (got ${png.length} bytes)`);
});
